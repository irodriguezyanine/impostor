/**
 * Categorías del juego Impostor Chile
 *
 * Edita este archivo para agregar más categorías y palabras.
 * Puedes agregar cientos de palabras por categoría.
 *
 * Al agregar una nueva categoría:
 * 1. Añade el objeto con id, name, icon y words
 * 2. Agrega wordHints con 3 pistas por palabra: Record<string, string[]>
 *    - Cada palabra debe tener 3 pistas que aparecen al azar (1 por impostor)
 *    - Si no encuentras pista para una palabra, se usará el nombre de la categoría
 * 3. Agrega la traducción en src/lib/i18n.ts en TRANSLATIONS[*].categories[id]
 */
export type Category = {
  id: string;
  name: string;
  icon: string; // Emoji o nombre de icono
  iconImage?: string; // Ruta opcional a imagen (ej: /logo-alamicos.png)
  words: string[]; // Las palabras secretas
  wordHints?: Record<string, string | string[]>; // 3 pistas por palabra (para impostores). Si es string, se usa como única pista.
};

/** Obtiene las 3 pistas para una palabra. Si no hay, usa el nombre de la categoría. */
export function getHintsForWord(category: Category, word: string): string[] {
  const normalize = (value: string) => value.trim().toLowerCase();
  const wordKey = normalize(word);

  const sanitize = (hint: string) =>
    normalize(hint) === wordKey ? category.name : hint;

  const raw = category.wordHints?.[word];
  if (Array.isArray(raw) && raw.length >= 1) {
    const hints = raw.filter(Boolean).map(sanitize).slice(0, 3);
    while (hints.length < 3) hints.push(category.name);
    return hints.slice(0, 3);
  }
  if (typeof raw === "string") {
    return [sanitize(raw), category.name, category.name].slice(0, 3);
  }
  return [category.name, category.name, category.name];
}

